import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import type { Framework } from '@usertax/core';
import { discoverApps, gitRoot, readPackageJson } from '@usertax/measure';
import type { DiscoveredApp } from '@usertax/measure';
import { EXIT, UsageError } from '../io.js';
import type { Io } from '../io.js';

export const INIT_HELP = `Usage:
  usertax init [options]

Sets up usertax in the current repository: writes the GitHub Actions workflows (and, with
--budget, a usertax.config.json), using the package manager and build script it detects.
Existing files are left alone unless --force is given.

Options:
      --single     One workflow that measures and comments (for repositories that do not
                   accept pull requests from forks). Default: the fork-safe pair of workflows.
      --budget     Also write usertax.config.json with a starter budget
      --force      Overwrite existing files
      --dry-run    Print the files instead of writing them
  -h, --help       Show this help
`;

export type PackageManager = 'npm' | 'pnpm' | 'yarn' | 'yarn-classic' | 'bun';

/** What `usertax init` found in a repository. */
export interface RepositoryInfo {
  readonly packageManager: PackageManager;
  /** Whether the repository has a lockfile (npm without one uses `npm install`). */
  readonly lockfile: boolean;
  /** `build` script of the root package.json, if there is one. */
  readonly hasBuildScript: boolean;
  readonly apps: readonly DiscoveredApp[];
  readonly defaultBranch: string;
}

// Third-party actions pinned by commit SHA (the same ones this repository's workflows use).
const ACTIONS = {
  checkout: 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1',
  setupNode: 'actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0',
  pnpm: 'pnpm/action-setup@ea17c68df8912ef543352723c149a84f56e3d413 # v6.1.0',
  bun: 'oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0',
  upload: 'actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9 # v7.0.2',
  download: 'actions/download-artifact@9000827ccba6bdab643e8b6fd33ac0654aef8333 # v8.0.2',
  usertax:
    'omerozkilic/usertax-action@v0 # zizmor: ignore[unpinned-uses] pin a commit SHA to freeze the action',
} as const;

/** Detects the package manager from the lockfile at the repository root (npm without one). */
export async function detectPackageManager(root: string): Promise<PackageManager> {
  const names = new Set(await readdir(root).catch(() => [] as string[]));
  if (names.has('pnpm-lock.yaml')) return 'pnpm';
  if (names.has('bun.lock') || names.has('bun.lockb')) return 'bun';
  if (names.has('yarn.lock')) {
    const lock = await readFile(join(root, 'yarn.lock'), 'utf8');
    return lock.includes('__metadata:') ? 'yarn' : 'yarn-classic';
  }
  return 'npm';
}

function setupSteps(pm: PackageManager, lockfile: boolean): string[] {
  const node = (cache?: string) => [
    `      - uses: ${ACTIONS.setupNode}`,
    '        with:',
    '          node-version: 24',
    ...(cache === undefined ? [] : [`          cache: ${cache}`]),
  ];
  switch (pm) {
    case 'pnpm':
      return [
        `      - uses: ${ACTIONS.pnpm}`,
        ...node('pnpm'),
        '      - run: pnpm install --frozen-lockfile',
      ];
    case 'yarn':
      return [...node(), '      - run: corepack enable && yarn install --immutable'];
    case 'yarn-classic':
      return [...node('yarn'), '      - run: yarn install --frozen-lockfile'];
    case 'bun':
      return [
        `      - uses: ${ACTIONS.bun}`,
        ...node(),
        '      - run: bun install --frozen-lockfile',
      ];
    case 'npm':
      return lockfile
        ? [...node('npm'), '      - run: npm ci']
        : [...node(), '      - run: npm install'];
  }
}

function runScript(pm: PackageManager): string {
  return pm === 'npm' ? 'npm run build' : pm === 'yarn-classic' ? 'yarn build' : `${pm} run build`;
}

function buildStep(info: RepositoryInfo): string[] {
  return info.hasBuildScript
    ? [
        `      - run: ${runScript(info.packageManager)} # build with source maps (see the notes of usertax init)`,
      ]
    : [
        '      # Replace with the command that builds your apps, with source maps:',
        `      - run: ${runScript(info.packageManager)}`,
      ];
}

const HEADER = '# Generated by `usertax init`. Docs: https://github.com/omerozkilic/usertax';

/** The measure workflow of the fork-safe pair, or the single workflow with `single`. */
export function measureWorkflow(info: RepositoryInfo, single: boolean): string {
  const permissions = single
    ? [
        'permissions:',
        '  contents: read',
        '  actions: read',
        '  pull-requests: write',
        '  statuses: write',
      ]
    : ['permissions:', '  contents: read'];
  return [
    HEADER,
    single
      ? '# Measures each pull request and comments on it in one job (no pull requests from forks).'
      : '# Step 1 of 2: builds and measures with a read-only token; usertax-comment.yml comments.',
    'name: usertax',
    'on:',
    '  pull_request:',
    '  push:',
    `    branches: [${info.defaultBranch}] # stores the base report that pull requests are compared with`,
    '  workflow_dispatch: # run on the default branch to recreate a missing base report',
    ...permissions,
    'jobs:',
    '  usertax:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    `      - uses: ${ACTIONS.checkout}`,
    '        with:',
    '          persist-credentials: false',
    ...setupSteps(info.packageManager, info.lockfile),
    ...buildStep(info),
    '      - id: usertax',
    `        uses: ${ACTIONS.usertax}`,
    '        with:',
    `          mode: ${single ? 'all' : 'measure'}`,
    `      - uses: ${ACTIONS.upload}`,
    '        if: always() && steps.usertax.outputs.report',
    '        with:',
    '          name: ${{ steps.usertax.outputs.artifact-name }}',
    '          path: ${{ steps.usertax.outputs.report }}',
    '          retention-days: 90',
    '',
  ].join('\n');
}

/** The comment workflow of the fork-safe pair: runs from the default branch, never PR code. */
export function commentWorkflow(): string {
  return [
    HEADER,
    '# Step 2 of 2: posts the comment from the default branch and reads the report as data.',
    'name: usertax comment',
    'on:',
    '  workflow_run: # zizmor: ignore[dangerous-triggers] default-branch code only; the report is untrusted data',
    '    workflows: [usertax]',
    '    types: [completed]',
    'permissions:',
    '  contents: read',
    '  actions: read',
    '  pull-requests: write',
    '  statuses: write',
    'jobs:',
    '  comment:',
    "    if: github.event.workflow_run.event == 'pull_request' && github.event.workflow_run.conclusion == 'success'",
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      # The default branch, never the pull request: your trusted configuration.',
    `      - uses: ${ACTIONS.checkout}`,
    '        with:',
    '          persist-credentials: false',
    `      - uses: ${ACTIONS.download}`,
    '        with:',
    '          name: usertax-head',
    '          run-id: ${{ github.event.workflow_run.id }}',
    '          github-token: ${{ github.token }}',
    '          path: .usertax-head',
    `      - uses: ${ACTIONS.usertax}`,
    '        with:',
    '          mode: comment',
    '          head-report: .usertax-head/usertax-report.json',
    '',
  ].join('\n');
}

const WEB: ReadonlySet<Framework> = new Set(['vite', 'next', 'astro', 'sveltekit', 'webpack']);
const MOBILE: ReadonlySet<Framework> = new Set(['expo', 'react-native']);

/** A starter configuration: route budgets for web apps, a warning budget for mobile bundles. */
export function starterConfig(apps: readonly DiscoveredApp[]): string {
  const budgets: Record<string, unknown>[] = [];
  if (apps.length === 0 || apps.some((a) => WEB.has(a.framework))) {
    budgets.push({ metric: 'route[*].js.gzip', maxIncrease: '10 kB' });
  }
  if (apps.some((a) => MOBILE.has(a.framework))) {
    budgets.push({ metric: 'bundle[*].raw', maxIncreasePercent: 2, level: 'warn' });
  }
  return `${JSON.stringify(
    {
      $schema:
        'https://raw.githubusercontent.com/omerozkilic/usertax/main/packages/core/schema/config.schema.json',
      budgets,
    },
    null,
    2,
  )}\n`;
}

/** Checks the build configuration of each app and says what usertax needs from it. */
export async function appNotes(root: string, apps: readonly DiscoveredApp[]): Promise<string[]> {
  const notes: string[] = [];
  const config = async (dir: string, prefix: string) => {
    const files = await readdir(join(root, dir)).catch(() => [] as string[]);
    const file = files.find((f) => f.startsWith(prefix) && /\.(?:[cm]?[jt]s)$/.test(f));
    return file === undefined ? undefined : readFile(join(root, dir, file), 'utf8');
  };
  for (const app of apps) {
    const where = app.path === '.' ? 'the root app' : app.path;
    if (app.framework === 'vite') {
      const text = (await config(app.path, 'vite.config.')) ?? '';
      if (!text.includes('sourcemap') || !text.includes('manifest')) {
        notes.push(
          `${where} (Vite): set build.sourcemap to 'hidden' and build.manifest to true in vite.config, for packages and routes.`,
        );
      }
    } else if (app.framework === 'next') {
      const text = (await config(app.path, 'next.config.')) ?? '';
      if (!text.includes('productionBrowserSourceMaps')) {
        notes.push(
          `${where} (Next.js): set productionBrowserSourceMaps: true in next.config, for packages.`,
        );
      }
    } else if (app.framework === 'astro') {
      const text = (await config(app.path, 'astro.config.')) ?? '';
      if (!text.includes('sourcemap')) {
        notes.push(
          `${where} (Astro): set vite: { build: { sourcemap: 'hidden' } } in astro.config, for packages.`,
        );
      }
    } else if (app.framework === 'sveltekit') {
      const text = (await config(app.path, 'vite.config.')) ?? '';
      if (!text.includes('sourcemap')) {
        notes.push(
          `${where} (SvelteKit): set build.sourcemap to 'hidden' in vite.config, for packages. Routes need adapter-static, which writes the prerendered pages.`,
        );
      }
    } else if (app.framework === 'webpack') {
      notes.push(`${where} (webpack): emit source maps (devtool: 'hidden-source-map').`);
    } else if (app.framework === 'expo') {
      notes.push(
        `${where} (Expo): the build must run \`npx expo export --source-maps\`, one platform at a time for reproducible bundles (--platform android, then ios).`,
      );
    } else {
      notes.push(
        `${where} (React Native): list its bundles (and optionally APK/AAB/IPA files) in usertax.config.json; see docs/configuration.md.`,
      );
    }
  }
  return notes;
}

async function exists(path: string): Promise<boolean> {
  return (await stat(path).catch(() => undefined)) !== undefined;
}

async function defaultBranch(root: string): Promise<string> {
  // A clone records the remote's default branch in refs/remotes/origin/HEAD.
  const remote = await readFile(
    join(root, '.git', 'refs', 'remotes', 'origin', 'HEAD'),
    'utf8',
  ).catch(() => '');
  const fromRemote = /^ref: refs\/remotes\/origin\/(.+)$/m.exec(remote)?.[1]?.trim();
  if (fromRemote !== undefined) return fromRemote;
  const head = await readFile(join(root, '.git', 'HEAD'), 'utf8').catch(() => '');
  const current = /^ref: refs\/heads\/(.+)$/m.exec(head)?.[1]?.trim();
  return current === 'master' ? 'master' : 'main';
}

export async function initCommand(
  argv: readonly string[],
  io: Io,
  context: { readonly cwd: string },
): Promise<number> {
  const { values, positionals } = parseArgs({
    args: [...argv],
    allowPositionals: true,
    strict: true,
    options: {
      single: { type: 'boolean' },
      budget: { type: 'boolean' },
      force: { type: 'boolean' },
      'dry-run': { type: 'boolean' },
      help: { type: 'boolean', short: 'h' },
    },
  });
  if (values.help === true) {
    io.stdout(INIT_HELP);
    return EXIT.ok;
  }
  if (positionals.length > 0) throw new UsageError(`unexpected argument ${positionals[0] ?? ''}`);

  const root = (await gitRoot(context.cwd)) ?? resolve(context.cwd);
  const manifest = await readPackageJson(root);
  if (manifest === undefined) {
    throw new UsageError(`no package.json at the repository root ${root}`);
  }
  const names = new Set(await readdir(root).catch(() => [] as string[]));
  const info: RepositoryInfo = {
    packageManager: await detectPackageManager(root),
    lockfile: [
      'pnpm-lock.yaml',
      'package-lock.json',
      'npm-shrinkwrap.json',
      'yarn.lock',
      'bun.lock',
      'bun.lockb',
    ].some((n) => names.has(n)),
    hasBuildScript:
      typeof (manifest as { scripts?: Record<string, unknown> }).scripts?.['build'] === 'string',
    apps: await discoverApps(root),
    defaultBranch: await defaultBranch(root),
  };
  const single = values.single === true;
  const files: { path: string; content: string }[] = [
    { path: '.github/workflows/usertax.yml', content: measureWorkflow(info, single) },
  ];
  if (!single) {
    files.push({ path: '.github/workflows/usertax-comment.yml', content: commentWorkflow() });
  }
  if (values.budget === true) {
    files.push({ path: 'usertax.config.json', content: starterConfig(info.apps) });
  }

  const dryRun = values['dry-run'] === true;
  const written: string[] = [];
  const skipped: string[] = [];
  for (const file of files) {
    const target = join(root, file.path);
    if (dryRun) {
      io.stdout(`--- ${file.path}\n${file.content}\n`);
      continue;
    }
    if (values.force !== true && (await exists(target))) {
      skipped.push(file.path);
      continue;
    }
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, file.content);
    written.push(file.path);
  }

  const lines: string[] = [];
  const apps =
    info.apps.length === 0
      ? 'no apps found yet (usertax looks for Vite, Next.js, webpack, Expo and React Native packages)'
      : info.apps.map((a) => `${a.path === '.' ? '.' : a.path} (${a.framework})`).join(', ');
  lines.push(`Package manager: ${info.packageManager} · apps: ${apps}`);
  if (!dryRun) {
    for (const path of written) lines.push(`created ${path}`);
    for (const path of skipped) lines.push(`skipped ${path} (exists; --force overwrites it)`);
  }
  const notes = await appNotes(root, info.apps);
  if (!info.hasBuildScript) {
    notes.unshift('No build script in package.json: edit the build step of usertax.yml.');
  }
  if (notes.length > 0)
    lines.push('', 'Before your first pull request:', ...notes.map((n) => `- ${n}`));
  if (!dryRun) {
    lines.push(
      '',
      `Next: commit the files and push them to ${info.defaultBranch}, so that usertax stores the first`,
      'base report. Pull requests opened after that get a comparison.',
    );
  }
  io.stdout(`${lines.join('\n')}\n`);
  return EXIT.ok;
}
