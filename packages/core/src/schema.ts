import { z } from 'zod';

/**
 * The usertax report: everything measured for one commit. See ADR 0003.
 *
 * Reports cross trust boundaries (artifacts produced by untrusted PR code), so every field
 * has bounds and every report read from outside the process goes through {@link parseReport}.
 * Unknown keys are stripped, which keeps additive schema changes compatible.
 */
export const REPORT_SCHEMA_VERSION = 1;

const bytes = z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER);
const shortText = z.string().min(1).max(200);
const pathText = z.string().min(1).max(1024);

export const compressionSchema = z.enum(['raw', 'gzip', 'brotli']);
export type Compression = z.infer<typeof compressionSchema>;

export const packageContributionSchema = z.object({
  /** npm package name. Bytes without a package (first-party code) are reported separately. */
  name: z.string().min(1).max(214),
  /** Minified bytes attributed to the package by the source map. */
  bytes,
  /**
   * Bytes per installed version, only when this file contains more than one version of the
   * package (a duplicate). Copies whose version could not be read are left out.
   */
  versions: z
    .array(z.object({ version: z.string().min(1).max(256), bytes }))
    .min(2)
    .max(50)
    .optional(),
});

export const moduleContributionSchema = z.object({
  /** Original source path from the source map, normalised to `/` separators. */
  path: pathText,
  package: z.string().min(1).max(214).optional(),
  bytes,
});

const sourceMapAttribution = {
  packages: z.array(packageContributionSchema).max(5000).optional(),
  /** First-party (non-`node_modules`) bytes according to the source map. */
  firstPartyBytes: bytes.optional(),
  /** Generated bytes the source map does not cover. */
  unattributedBytes: bytes.optional(),
  /** Largest modules; collectors may truncate this list. */
  modules: z.array(moduleContributionSchema).max(5000).optional(),
};

export const assetTypeSchema = z.enum([
  'js',
  'css',
  'html',
  'font',
  'image',
  'json',
  'wasm',
  'other',
]);
export type AssetType = z.infer<typeof assetTypeSchema>;

export const assetSchema = z.object({
  /** Identity across builds, e.g. the output path with its content hash removed. */
  key: z.string().min(1).max(512),
  /** Actual output path, relative to the app's output directory. */
  file: pathText,
  type: assetTypeSchema,
  raw: bytes,
  gzip: bytes.optional(),
  brotli: bytes.optional(),
  ...sourceMapAttribution,
});
export type Asset = z.infer<typeof assetSchema>;

export const routeSchema = z.object({
  route: z.string().min(1).max(512),
  /** Keys of the assets loaded for this route. */
  assets: z.array(z.string().min(1).max(512)).max(1000),
});
export type Route = z.infer<typeof routeSchema>;

export const platformSchema = z.enum(['ios', 'android']);
export type Platform = z.infer<typeof platformSchema>;

export const jsBundleSchema = z.object({
  platform: platformSchema,
  file: pathText,
  format: z.enum(['js', 'hermes']),
  raw: bytes,
  gzip: bytes.optional(),
  brotli: bytes.optional(),
  ...sourceMapAttribution,
});
export type JsBundle = z.infer<typeof jsBundleSchema>;

export const archiveCategorySchema = z.enum([
  'js-bundle',
  'dex',
  'native',
  'resources',
  'assets',
  'binary',
  'frameworks',
  'other',
]);
export type ArchiveCategory = z.infer<typeof archiveCategorySchema>;

export const archiveSchema = z.object({
  /** Identity across builds, e.g. `android` or a name from the configuration. */
  key: z.string().min(1).max(200),
  file: pathText,
  format: z.enum(['apk', 'aab', 'ipa']),
  platform: platformSchema,
  /** Size of the archive file on disk. */
  fileSize: bytes,
  entryCount: z.number().int().nonnegative(),
  categories: z
    .array(
      z.object({
        category: archiveCategorySchema,
        compressed: bytes,
        uncompressed: bytes,
        count: z.number().int().nonnegative(),
      }),
    )
    .max(20),
  entries: z
    .array(
      z.object({
        path: pathText,
        category: archiveCategorySchema,
        compressed: bytes,
        uncompressed: bytes,
      }),
    )
    .max(50_000),
  /** Entries left out of `entries` by the collector, aggregated. */
  omittedEntries: z
    .object({ count: z.number().int().nonnegative(), compressed: bytes, uncompressed: bytes })
    .optional(),
});
export type Archive = z.infer<typeof archiveSchema>;

export const lighthouseContaminationSchema = z.object({
  /**
   * Origins of browser extensions whose requests or scripts appeared in the run, such as
   * `chrome-extension://<id>`. Their code is attributed to the page, so the run is not comparable.
   */
  origins: z.array(z.string().min(1).max(200)).min(1).max(20),
  /** Distinct extension URLs seen in the run (requests and scripts). */
  requestCount: z.number().int().nonnegative(),
});
export type LighthouseContamination = z.infer<typeof lighthouseContaminationSchema>;

export const lighthouseRunSchema = z.object({
  /** Performance score, 0–100. */
  performance: z.number().min(0).max(100),
  /** Largest Contentful Paint in milliseconds. */
  lcp: z.number().nonnegative(),
  /** Total Blocking Time in milliseconds. */
  tbt: z.number().nonnegative(),
  /** Cumulative Layout Shift (unitless). */
  cls: z.number().nonnegative(),
  /** Present when browser extensions were active in the run; see {@link lighthouseContaminationSchema}. */
  contamination: lighthouseContaminationSchema.optional(),
});
export type LighthouseRun = z.infer<typeof lighthouseRunSchema>;

export const lighthouseSchema = z.object({
  /** Page identity, usually a path such as `/` or `/pricing`. */
  url: z.string().min(1).max(512),
  formFactor: z.enum(['mobile', 'desktop']),
  lighthouseVersion: z.string().min(1).max(50),
  runs: z.array(lighthouseRunSchema).min(1).max(100),
});
export type Lighthouse = z.infer<typeof lighthouseSchema>;

export const dependencySchema = z.object({
  name: z.string().min(1).max(214),
  version: z.string().min(1).max(256),
  /** Declared in the app's own package.json (as opposed to transitive). */
  direct: z.boolean(),
  /** Only reachable through dev dependencies. */
  dev: z.boolean().optional(),
  /** For transitive dependencies: up to three direct dependencies that pull it in. */
  via: z.array(z.string().min(1).max(214)).max(3).optional(),
});
export type Dependency = z.infer<typeof dependencySchema>;

export const appKindSchema = z.enum(['web', 'react-native']);
export const frameworkSchema = z.enum([
  'vite',
  'next',
  'webpack',
  'expo',
  'react-native',
  'static',
  'other',
]);
export type Framework = z.infer<typeof frameworkSchema>;

export const appSchema = z.object({
  /** Identity across reports; unique within a report. */
  id: z
    .string()
    .min(1)
    .max(200)
    .regex(/^[\w@./-]+$/, 'app ids may contain letters, digits, _, @, ., / and -'),
  name: shortText,
  /** Directory of the app relative to the repository root (`.` for the root). */
  path: pathText,
  kind: appKindSchema,
  framework: frameworkSchema,
  assets: z.array(assetSchema).max(10_000).optional(),
  routes: z.array(routeSchema).max(2000).optional(),
  bundles: z.array(jsBundleSchema).max(10).optional(),
  archives: z.array(archiveSchema).max(20).optional(),
  lighthouse: z.array(lighthouseSchema).max(50).optional(),
  dependencies: z.array(dependencySchema).max(50_000).optional(),
});
export type App = z.infer<typeof appSchema>;

export const reportSchema = z
  .object({
    schemaVersion: z.literal(REPORT_SCHEMA_VERSION),
    tool: z.object({ name: z.literal('usertax'), version: z.string().min(1).max(50) }),
    createdAt: z.iso.datetime(),
    git: z
      .object({
        sha: z.string().regex(/^[0-9a-f]{40}([0-9a-f]{24})?$/, 'expected a full commit SHA'),
        ref: z.string().min(1).max(256).optional(),
      })
      .optional(),
    settings: z.object({
      compression: z.object({
        gzipLevel: z.number().int().min(1).max(9),
        brotliQuality: z.number().int().min(0).max(11),
      }),
    }),
    environment: z
      .object({
        os: z.string().max(100).optional(),
        node: z.string().max(50).optional(),
        cpu: z.string().max(200).optional(),
      })
      .optional(),
    apps: z.array(appSchema).max(100),
  })
  .superRefine((report, ctx) => {
    const seen = new Set<string>();
    for (const [index, app] of report.apps.entries()) {
      if (seen.has(app.id)) {
        ctx.addIssue({
          code: 'custom',
          path: ['apps', index, 'id'],
          message: `duplicate app id "${app.id}"`,
        });
      }
      seen.add(app.id);
    }
  });
export type Report = z.infer<typeof reportSchema>;

/** Thrown when a report does not match the schema. `issues` are human-readable. */
export class ReportValidationError extends Error {
  readonly issues: readonly string[];

  constructor(message: string, issues: readonly string[]) {
    super(issues.length > 0 ? `${message}:\n- ${issues.join('\n- ')}` : message);
    this.name = 'ReportValidationError';
    this.issues = issues;
  }
}

const MAX_REPORTED_ISSUES = 20;

/** Validates untrusted input as a report. Throws {@link ReportValidationError}. */
export function parseReport(input: unknown): Report {
  if (typeof input === 'object' && input !== null && 'schemaVersion' in input) {
    const version = input.schemaVersion;
    if (typeof version === 'number' && version > REPORT_SCHEMA_VERSION) {
      throw new ReportValidationError(
        `report schema version ${version} is newer than this usertax supports (${REPORT_SCHEMA_VERSION}); upgrade usertax`,
        [],
      );
    }
  }
  const result = reportSchema.safeParse(input);
  if (result.success) {
    return result.data;
  }
  const issues = result.error.issues
    .slice(0, MAX_REPORTED_ISSUES)
    .map((issue) => `${issue.path.length > 0 ? issue.path.join('.') : '(root)'}: ${issue.message}`);
  if (result.error.issues.length > MAX_REPORTED_ISSUES) {
    issues.push(`…and ${result.error.issues.length - MAX_REPORTED_ISSUES} more`);
  }
  throw new ReportValidationError('invalid usertax report', issues);
}

/** JSON Schema (draft 2020-12) of the report, for other tools. */
export function reportJsonSchema(): Record<string, unknown> {
  return z.toJSONSchema(reportSchema, { target: 'draft-2020-12', io: 'input' });
}
